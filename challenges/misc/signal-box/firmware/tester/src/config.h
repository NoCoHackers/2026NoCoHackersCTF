#ifndef SIGNAL_BOX_TESTER_CONFIG_H
#define SIGNAL_BOX_TESTER_CONFIG_H

#define TESTER_FIRMWARE_VERSION "0.3.0"

// XIAO labels: D1=GPIO27, D2=GPIO28, D3=GPIO29, D4=GPIO6, D5=GPIO7.
#define DUT_3V3_ADC_GPIO 27u
#define DUT_3V3_ADC_CHANNEL 1u
#define DUT_SDA_GPIO 28u
#define DUT_SCL_GPIO 29u
#define DUT_UART_TX_TESTER_RX_GPIO 6u
#define DUT_UART_RX_TESTER_TX_GPIO 7u

#define TESTER_LOG_TX_GPIO 0u
#define TESTER_LOG_RX_GPIO 1u
#define TESTER_LOG_BAUD 115200u
#define TESTER_MODE_GPIO 3u // XIAO D10; HIGH=WP on, LOW=WP off.

#define TESTER_GREEN_LED_GPIO 16u
#define TESTER_RED_LED_GPIO 17u
#define TESTER_BLUE_LED_GPIO 25u

#define DUT_UART_BAUD 115200u
#define DUT_BOOT_TIMEOUT_US 30000000u
#define DUT_COMMAND_TIMEOUT_US 30000000u
#define DUT_REMOVAL_FILTER_US 250000u
#define DUT_POWER_SETTLE_US 500000u
#define DUT_POWER_POLL_US 10000u

// With a 10 kΩ / 10 kΩ divider and a calibrated 3.300 V tester rail,
// 3.15-3.45 V at the DUT corresponds to ADC codes 1955-2140.
#define DUT_3V3_ADC_MIN 1955u
#define DUT_3V3_ADC_MAX 2140u
#define DUT_3V3_ADC_PRESENT_MIN 800u
#define DUT_3V3_ADC_SAMPLES 16u

#endif
