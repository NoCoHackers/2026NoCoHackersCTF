#!/usr/bin/env sh
# Concatenate tokens.css + theme.css into theme.bundle.css.
# Authors link one file; we keep two sources so tokens stay reviewable.
set -eu
cd "$(dirname "$0")/.."
{
  printf '/* NoCo Hackers CTF 2026 - bundle (tokens.css + theme.css).\n'
  printf '   Generated by tools/build-theme.sh; edit the sources, not this file. */\n\n'
  cat theme/tokens.css
  printf '\n'
  grep -v '^@import "tokens.css";$' theme/theme.css
} > theme/theme.bundle.css
echo "wrote theme/theme.bundle.css ($(wc -c < theme/theme.bundle.css) bytes)"
